package com.cupet.fallingball.learning

import com.cupet.fallingball.analysis.MeasurementRecord
import org.json.JSONArray
import org.json.JSONObject
import java.io.File
import java.nio.file.AtomicMoveNotSupportedException
import java.nio.file.Files
import java.nio.file.StandardCopyOption

/** Versioned, atomic local persistence for all learning state. */
class LearningStore(private val root: File) {

    @Synchronized
    fun saveQuestions(value: PreparedQuestions) {
        validateMeasurementId(value.measurementId)
        require(FINGERPRINT.matches(value.fingerprint)) { "Invalid fingerprint" }
        val directory = measurementDirectory(value.measurementId).resolve("questions")
        atomicWrite(directory.resolve("${value.fingerprint}.json"), questionJson(value))
    }

    @Synchronized
    fun loadQuestions(measurementId: String, fingerprint: String): PreparedQuestions? {
        validateMeasurementId(measurementId)
        require(FINGERPRINT.matches(fingerprint)) { "Invalid fingerprint" }
        val file = measurementDirectory(measurementId)
            .resolve("questions")
            .resolve("$fingerprint.json")
        return readJson(file)?.let(::questionsFromJson)
    }

    @Synchronized
    fun openSession(record: MeasurementRecord, requestedSessionId: String? = null): LearningSession {
        val snapshot = LearningMeasurementSnapshot.fromRecord(record)
        if (requestedSessionId != null) {
            val requested = loadSession(record.id, requestedSessionId)
            if (requested != null) return requested
        }
        val resumable = listSessions(record.id)
            .filter { it.status == LearningSessionStatus.ACTIVE }
            .maxByOrNull { it.updatedAtEpochMs }
        if (resumable != null && resumable.measurementFingerprint == snapshot.fingerprint) {
            return resumable
        }
        return createSession(snapshot)
    }

    @Synchronized
    fun createSession(snapshot: LearningMeasurementSnapshot): LearningSession {
        validateMeasurementId(snapshot.measurementId)
        pauseActiveSessions(snapshot.measurementId)
        val now = System.currentTimeMillis()
        val session = LearningSession(
            measurementId = snapshot.measurementId,
            measurementFingerprint = snapshot.fingerprint,
            title = snapshot.recordName.ifBlank { "本次数据学习" },
            createdAtEpochMs = now,
            updatedAtEpochMs = now,
            snapshot = snapshot
        )
        saveSession(session)
        return session
    }

    @Synchronized
    fun activateSession(measurementId: String, sessionId: String): LearningSession {
        val session = requireNotNull(loadSession(measurementId, sessionId)) {
            "Learning session does not exist"
        }
        require(session.status != LearningSessionStatus.ENDED) {
            "Ended learning session cannot be resumed"
        }
        pauseActiveSessions(measurementId, exceptSessionId = sessionId)
        return session.copy(
            status = LearningSessionStatus.ACTIVE,
            updatedAtEpochMs = System.currentTimeMillis()
        ).also(::saveSession)
    }

    @Synchronized
    fun endSession(measurementId: String, sessionId: String): LearningSession {
        val session = requireNotNull(loadSession(measurementId, sessionId)) {
            "Learning session does not exist"
        }
        return session.copy(
            status = LearningSessionStatus.ENDED,
            updatedAtEpochMs = System.currentTimeMillis()
        ).also(::saveSession)
    }

    @Synchronized
    fun renameSession(measurementId: String, sessionId: String, title: String): LearningSession {
        validateMeasurementId(measurementId)
        validateSessionId(sessionId)
        val session = requireNotNull(loadSessionFile(
            sessionsDirectory(measurementId).resolve("$sessionId.json"),
            recoverInterrupted = false
        )) {
            "Learning session does not exist"
        }
        val cleaned = cleanTitle(title)
        return session.copy(
            title = cleaned,
            titleUserRenamed = true,
            titleAutoGenerated = false,
            updatedAtEpochMs = System.currentTimeMillis()
        )
            .also(::writeSession)
    }

    /** Applies the first-user-message title without taking title ownership from the user. */
    @Synchronized
    fun applyProvisionalTitle(
        measurementId: String,
        sessionId: String,
        expectedTitle: String,
        provisionalTitle: String
    ): LearningSession? {
        validateMeasurementId(measurementId)
        validateSessionId(sessionId)
        val session = loadSessionFile(
            sessionsDirectory(measurementId).resolve("$sessionId.json"),
            recoverInterrupted = false
        ) ?: return null
        if (session.title != expectedTitle || session.titleUserRenamed ||
            session.titleAutoGenerated
        ) return null
        return session.copy(
            title = cleanTitle(provisionalTitle),
            updatedAtEpochMs = System.currentTimeMillis()
        ).also(::writeSession)
    }

    /** Applies an asynchronous generated title only while the provisional title is unchanged. */
    @Synchronized
    fun applyGeneratedTitle(
        measurementId: String,
        sessionId: String,
        expectedTitle: String,
        generatedTitle: String
    ): LearningSession? {
        validateMeasurementId(measurementId)
        validateSessionId(sessionId)
        val session = loadSessionFile(
            sessionsDirectory(measurementId).resolve("$sessionId.json"),
            recoverInterrupted = false
        ) ?: return null
        if (session.title != expectedTitle || session.titleUserRenamed ||
            session.titleAutoGenerated
        ) return null
        return session.copy(
            title = cleanTitle(generatedTitle),
            titleAutoGenerated = true,
            updatedAtEpochMs = System.currentTimeMillis()
        ).also(::writeSession)
    }

    @Synchronized
    fun saveSession(session: LearningSession) {
        validateMeasurementId(session.measurementId)
        validateSessionId(session.id)
        val file = sessionsDirectory(session.measurementId).resolve("${session.id}.json")
        // Do not run interrupted-stream recovery while an active Tutor is saving a newer copy.
        val existing = readJson(file)?.let(::sessionFromJson)
        val value = if (existing != null) {
            // General state snapshots never own title state. A stale streaming snapshot may
            // carry any combination of title flags, so conditional merging is insufficient.
            session.copy(
                title = existing.title,
                titleUserRenamed = existing.titleUserRenamed,
                titleAutoGenerated = existing.titleAutoGenerated
            )
        } else {
            session
        }
        writeSession(value)
    }

    private fun writeSession(session: LearningSession) {
        validateMeasurementId(session.measurementId)
        validateSessionId(session.id)
        atomicWrite(
            sessionsDirectory(session.measurementId).resolve("${session.id}.json"),
            sessionJson(session)
        )
    }

    private fun cleanTitle(value: String): String =
        value.trim().replace(Regex("\\s+"), " ").take(48).also {
            require(it.isNotBlank()) { "Session title cannot be blank" }
        }

    @Synchronized
    fun loadSession(measurementId: String, sessionId: String): LearningSession? {
        validateMeasurementId(measurementId)
        validateSessionId(sessionId)
        return loadSessionFile(sessionsDirectory(measurementId).resolve("$sessionId.json"))
    }

    @Synchronized
    fun listSessions(measurementId: String): List<LearningSession> {
        validateMeasurementId(measurementId)
        return sessionsDirectory(measurementId).listFiles { file ->
            file.isFile && file.extension == "json"
        }?.mapNotNull { loadSessionFile(it, recoverInterrupted = false) }
            ?.sortedWith(
                compareByDescending<LearningSession> { it.createdAtEpochMs }
                    .thenByDescending { it.id }
            )
            .orEmpty()
    }

    @Synchronized
    fun deleteMeasurement(measurementId: String): Boolean {
        validateMeasurementId(measurementId)
        val directory = measurementDirectory(measurementId)
        if (!directory.exists()) return true
        val canonicalRoot = root.canonicalFile
        val canonicalTarget = directory.canonicalFile
        require(canonicalTarget.parentFile == canonicalRoot) { "Unsafe learning delete target" }
        return canonicalTarget.deleteRecursively()
    }

    private fun pauseActiveSessions(measurementId: String, exceptSessionId: String? = null) {
        listSessions(measurementId).forEach { session ->
            if (session.status == LearningSessionStatus.ACTIVE && session.id != exceptSessionId) {
                saveSession(
                    session.copy(
                        status = LearningSessionStatus.PAUSED,
                        updatedAtEpochMs = System.currentTimeMillis()
                    )
                )
            }
        }
    }

    private fun readJson(file: File): JSONObject? = if (!file.isFile) null else runCatching {
        JSONObject(file.readText(Charsets.UTF_8)).also {
            require(it.getInt("schema_version") == SCHEMA_VERSION) {
                "Unsupported learning schema"
            }
        }
    }.getOrNull()

    private fun loadSessionFile(file: File, recoverInterrupted: Boolean = true): LearningSession? {
        val loaded = readJson(file)?.let(::sessionFromJson) ?: return null
        if (!recoverInterrupted) return loaded
        val recovered = loaded.recoverInterruptedGeneration()
        if (recovered != loaded) atomicWrite(file, sessionJson(recovered))
        return recovered
    }

    private fun LearningSession.recoverInterruptedGeneration(): LearningSession {
        val hasInterruptedMessage = messages.any { it.state == LearningMessageState.STREAMING }
        val hasInterruptedAction = actions.any { it.state == LearningActionState.RUNNING }
        if (!hasInterruptedMessage && !hasInterruptedAction) return this
        val recoveredAt = System.currentTimeMillis()
        return copy(
            updatedAtEpochMs = maxOf(updatedAtEpochMs, recoveredAt),
            messages = messages.map { message ->
                if (message.state == LearningMessageState.STREAMING) {
                    message.copy(state = LearningMessageState.STOPPED)
                } else message
            },
            actions = actions.map { action ->
                if (action.state == LearningActionState.RUNNING) {
                    action.copy(
                        completedAtEpochMs = recoveredAt,
                        state = LearningActionState.ERROR,
                        resultSummary = action.resultSummary.ifBlank { "上次生成被中断" }
                    )
                } else action
            }
        )
    }

    private fun atomicWrite(target: File, value: JSONObject) {
        val directory = requireNotNull(target.parentFile)
        check(directory.exists() || directory.mkdirs()) { "Cannot create learning directory" }
        val temporary = directory.resolve(".${target.name}.tmp")
        try {
            temporary.writeText(value.toString(), Charsets.UTF_8)
            try {
                Files.move(
                    temporary.toPath(),
                    target.toPath(),
                    StandardCopyOption.ATOMIC_MOVE,
                    StandardCopyOption.REPLACE_EXISTING
                )
            } catch (_: AtomicMoveNotSupportedException) {
                Files.move(
                    temporary.toPath(),
                    target.toPath(),
                    StandardCopyOption.REPLACE_EXISTING
                )
            }
        } finally {
            if (temporary.exists()) temporary.delete()
        }
    }

    private fun measurementDirectory(measurementId: String) = root.resolve(measurementId)

    private fun sessionsDirectory(measurementId: String) =
        measurementDirectory(measurementId).resolve("sessions")

    private fun validateMeasurementId(value: String) {
        require(SAFE_ID.matches(value)) { "Invalid measurement id" }
    }

    private fun validateSessionId(value: String) {
        require(SAFE_ID.matches(value)) { "Invalid session id" }
    }

    private fun questionJson(value: PreparedQuestions) = versionedJson()
        .put("measurement_id", value.measurementId)
        .put("fingerprint", value.fingerprint)
        .put("generated_at", value.generatedAtEpochMs)
        .put("questions", JSONArray(value.questions))

    private fun questionsFromJson(value: JSONObject) = PreparedQuestions(
        measurementId = value.getString("measurement_id"),
        fingerprint = value.getString("fingerprint"),
        generatedAtEpochMs = value.getLong("generated_at"),
        questions = LearningQuestionValidator.validate(value.getJSONArray("questions").strings())
    )

    private fun sessionJson(value: LearningSession) = versionedJson()
        .put("id", value.id)
        .put("measurement_id", value.measurementId)
        .put("measurement_fingerprint", value.measurementFingerprint)
        .put("title", value.title)
        .put("title_user_renamed", value.titleUserRenamed)
        .put("title_auto_generated", value.titleAutoGenerated)
        .put("status", value.status.name)
        .put("created_at", value.createdAtEpochMs)
        .put("updated_at", value.updatedAtEpochMs)
        .put("snapshot", snapshotJson(value.snapshot))
        .put("learning_state", learningStateJson(value.learningState))
        .put("rolling_summary", value.rollingSummary)
        .put("messages", JSONArray(value.messages.map(::messageJson)))
        .put("actions", JSONArray(value.actions.map(::actionJson)))
        .put("references", JSONArray(value.references.map(::referenceJson)))

    private fun sessionFromJson(value: JSONObject) = LearningSession(
        id = value.getString("id"),
        measurementId = value.getString("measurement_id"),
        measurementFingerprint = value.getString("measurement_fingerprint"),
        title = value.getString("title"),
        titleUserRenamed = if (value.has("title_user_renamed")) {
            value.optBoolean("title_user_renamed")
        } else {
            inferLegacyManualTitle(value)
        },
        titleAutoGenerated = value.optBoolean("title_auto_generated", false),
        status = LearningSessionStatus.valueOf(value.getString("status")),
        createdAtEpochMs = value.getLong("created_at"),
        updatedAtEpochMs = value.getLong("updated_at"),
        snapshot = snapshotFromJson(value.getJSONObject("snapshot")),
        learningState = learningStateFromJson(value.getJSONObject("learning_state")),
        rollingSummary = value.getString("rolling_summary"),
        messages = value.getJSONArray("messages").objects().map(::messageFromJson),
        actions = value.getJSONArray("actions").objects().map(::actionFromJson),
        references = value.getJSONArray("references").objects().map(::referenceFromJson)
    )

    private fun inferLegacyManualTitle(value: JSONObject): Boolean {
        val title = value.optString("title")
        val recordName = value.optJSONObject("snapshot")?.optString("record_name").orEmpty()
        val initialTitle = recordName.ifBlank { "本次数据学习" }
        if (title == initialTitle) return false
        val messages = value.optJSONArray("messages") ?: return true
        val firstUser = messages.objects().firstOrNull {
            it.optString("role") == LearningMessageRole.USER.name
        }?.optString("text").orEmpty()
        val provisional = firstUser.trim().replace(Regex("\\s+"), " ").take(30)
        return provisional.isBlank() || title != provisional
    }

    private fun snapshotJson(value: LearningMeasurementSnapshot) = JSONObject()
        .put("measurement_id", value.measurementId)
        .put("fingerprint", value.fingerprint)
        .put("recorded_at", value.recordedAtEpochMs)
        .put("record_name", value.recordName)
        .put("liquid_name", value.liquidName)
        .put("sphere_material", value.sphereMaterial)
        .putNullable("temperature_c", value.temperatureC)
        .put("notes", value.notes)
        .put("resolution", value.resolutionLabel)
        .put("end_reason", value.endReason)
        .put("tick_spacing_mm", value.tickSpacingMm)
        .put("expected_tick_count", value.expectedTickCount)
        .put("facts", factsJson(value.facts))
        .put("diagnostics", JSONObject(value.diagnostics))
        .put("trajectory", JSONArray(value.trajectory.map(::trajectoryJson)))

    private fun snapshotFromJson(value: JSONObject) = LearningMeasurementSnapshot(
        measurementId = value.getString("measurement_id"),
        fingerprint = value.getString("fingerprint"),
        recordedAtEpochMs = value.getLong("recorded_at"),
        recordName = value.getString("record_name"),
        liquidName = value.getString("liquid_name"),
        sphereMaterial = value.getString("sphere_material"),
        temperatureC = value.nullableDouble("temperature_c"),
        notes = value.getString("notes"),
        resolutionLabel = value.getString("resolution"),
        endReason = value.getString("end_reason"),
        tickSpacingMm = value.getDouble("tick_spacing_mm").toFloat(),
        expectedTickCount = value.getInt("expected_tick_count"),
        facts = factsFromJson(value.getJSONObject("facts")),
        diagnostics = value.getJSONObject("diagnostics").keys().asSequence()
            .associateWith { value.getJSONObject("diagnostics").getString(it) },
        trajectory = value.getJSONArray("trajectory").objects().map(::trajectoryFromJson)
    )

    private fun factsJson(value: LearningMeasurementFacts) = JSONObject()
        .putNullable("terminal_velocity", value.terminalVelocityMmPerS)
        .putNullable("mean_velocity", value.meanVelocityMmPerS)
        .putNullable("r2", value.fittedR2)
        .putNullable("fit_start", value.fitStartMm)
        .putNullable("fit_end", value.fitEndMm)
        .putNullable("fit_duration", value.fitDurationMs)
        .putNullable("corrected_viscosity", value.correctedViscosityPaS)
        .putNullable("uncorrected_viscosity", value.uncorrectedViscosityPaS)
        .putNullable("wall_model", value.wallCorrectionModel)
        .putNullable("reynolds", value.reynoldsNumber)
        .put("sample_count", value.sampleCount)
        .put("valid_sample_count", value.validSampleCount)
        .put("effective_fps", value.effectiveSampleRateFps)
        .put("outlier_count", value.outlierSampleCount)
        .put("wall_contact_count", value.wallContactSampleCount)
        .put("wall_known_count", value.wallContactKnownSampleCount)
        .putNullable("average_center_offset", value.averageCenterOffsetMm)
        .putNullable("sphere_diameter", value.sphereDiameterMm)
        .putNullable("tube_diameter", value.tubeInnerDiameterMm)
        .putNullable("liquid_density", value.liquidDensityGPerCm3)
        .putNullable("sphere_density", value.sphereDensityGPerCm3)
        .put("reliable_terminal", value.reliableTerminalEstimate)
        .put("diagnostics_available", value.diagnosticsAvailable)

    private fun factsFromJson(value: JSONObject) = LearningMeasurementFacts(
        terminalVelocityMmPerS = value.nullableFloat("terminal_velocity"),
        meanVelocityMmPerS = value.nullableFloat("mean_velocity"),
        fittedR2 = value.nullableFloat("r2"),
        fitStartMm = value.nullableFloat("fit_start"),
        fitEndMm = value.nullableFloat("fit_end"),
        fitDurationMs = value.nullableLong("fit_duration"),
        correctedViscosityPaS = value.nullableDouble("corrected_viscosity"),
        uncorrectedViscosityPaS = value.nullableDouble("uncorrected_viscosity"),
        wallCorrectionModel = value.nullableString("wall_model"),
        reynoldsNumber = value.nullableDouble("reynolds"),
        sampleCount = value.getInt("sample_count"),
        validSampleCount = value.getInt("valid_sample_count"),
        effectiveSampleRateFps = value.getDouble("effective_fps").toFloat(),
        outlierSampleCount = value.getInt("outlier_count"),
        wallContactSampleCount = value.getInt("wall_contact_count"),
        wallContactKnownSampleCount = value.getInt("wall_known_count"),
        averageCenterOffsetMm = value.nullableFloat("average_center_offset"),
        sphereDiameterMm = value.nullableDouble("sphere_diameter"),
        tubeInnerDiameterMm = value.nullableDouble("tube_diameter"),
        liquidDensityGPerCm3 = value.nullableDouble("liquid_density"),
        sphereDensityGPerCm3 = value.nullableDouble("sphere_density"),
        reliableTerminalEstimate = value.getBoolean("reliable_terminal"),
        diagnosticsAvailable = value.getBoolean("diagnostics_available")
    )

    private fun trajectoryJson(value: LearningTrajectoryPoint) = JSONObject()
        .put("elapsed_ms", value.elapsedMs)
        .putNullable("position_ticks", value.positionTicks)
        .putNullable("position_mm", value.positionMm)
        .putNullable("velocity", value.velocityMmPerS)
        .putNullable("lateral_mm", value.lateralMm)
        .put("ruler_valid", value.rulerValid)
        .put("in_fit", value.usedInTerminalFit)
        .put("outlier", value.excludedAsOutlier)
        .put("wall", value.wallContactState)
        .put("source", value.detectionSource)
        .putNullable("confidence", value.detectionConfidence)

    private fun trajectoryFromJson(value: JSONObject) = LearningTrajectoryPoint(
        elapsedMs = value.getDouble("elapsed_ms").toFloat(),
        positionTicks = value.nullableFloat("position_ticks"),
        positionMm = value.nullableFloat("position_mm"),
        velocityMmPerS = value.nullableFloat("velocity"),
        lateralMm = value.nullableFloat("lateral_mm"),
        rulerValid = value.getBoolean("ruler_valid"),
        usedInTerminalFit = value.getBoolean("in_fit"),
        excludedAsOutlier = value.getBoolean("outlier"),
        wallContactState = value.getString("wall"),
        detectionSource = value.getString("source"),
        detectionConfidence = value.nullableFloat("confidence")
    )

    private fun learningStateJson(value: LearningState) = JSONObject()
        .put("current_goal", value.currentGoal)
        .put("unresolved", JSONArray(value.unresolvedQuestions))
        .put("mastered", JSONArray(value.masteredConcepts))
        .put("learner_level", value.learnerLevel)
        .put("updated_at", value.updatedAtEpochMs)

    private fun learningStateFromJson(value: JSONObject) = LearningState(
        currentGoal = value.getString("current_goal"),
        unresolvedQuestions = value.getJSONArray("unresolved").strings(),
        masteredConcepts = value.getJSONArray("mastered").strings(),
        learnerLevel = value.getString("learner_level"),
        updatedAtEpochMs = value.getLong("updated_at")
    )

    private fun messageJson(value: LearningMessage) = JSONObject()
        .put("id", value.id).put("role", value.role.name).put("text", value.text)
        .put("reasoning", value.reasoning)
        .put("attachments", JSONArray(value.attachmentNames))
        .put("turn_id", value.turnId)
        .put("created_at", value.createdAtEpochMs).put("state", value.state.name)

    private fun messageFromJson(value: JSONObject) = LearningMessage(
        id = value.getString("id"),
        role = LearningMessageRole.valueOf(value.getString("role")),
        text = value.getString("text"),
        reasoning = value.optString("reasoning"),
        attachmentNames = value.optJSONArray("attachments")?.strings().orEmpty(),
        turnId = value.optString("turn_id"),
        createdAtEpochMs = value.getLong("created_at"),
        state = LearningMessageState.valueOf(value.getString("state"))
    )

    private fun actionJson(value: LearningAction) = JSONObject()
        .put("id", value.id).put("turn_id", value.turnId).put("tool", value.toolName)
        .put("label", value.label).put("started_at", value.startedAtEpochMs)
        .put("call_id", value.callId).put("arguments", value.arguments)
        .put("output", value.output)
        .put("output_item", value.outputItemJson)
        .putNullable("completed_at", value.completedAtEpochMs).put("state", value.state.name)
        .put("result", value.resultSummary)

    private fun actionFromJson(value: JSONObject) = LearningAction(
        id = value.getString("id"),
        turnId = value.getString("turn_id"),
        toolName = value.getString("tool"),
        label = value.getString("label"),
        callId = value.optString("call_id"),
        arguments = value.optString("arguments", "{}"),
        output = value.optString("output"),
        outputItemJson = value.optString("output_item"),
        startedAtEpochMs = value.getLong("started_at"),
        completedAtEpochMs = value.nullableLong("completed_at"),
        state = LearningActionState.valueOf(value.getString("state")),
        resultSummary = value.getString("result")
    )

    private fun referenceJson(value: LearningReference) = JSONObject()
        .put("id", value.id).put("turn_id", value.turnId).put("title", value.title)
        .put("source", value.source).putNullable("url", value.url)

    private fun referenceFromJson(value: JSONObject) = LearningReference(
        id = value.getString("id"),
        turnId = value.getString("turn_id"),
        title = value.getString("title"),
        source = value.getString("source"),
        url = value.nullableString("url")
    )

    private fun versionedJson() = JSONObject().put("schema_version", SCHEMA_VERSION)

    private fun JSONObject.putNullable(key: String, value: Any?): JSONObject =
        put(key, value ?: JSONObject.NULL)

    private fun JSONObject.nullableDouble(key: String): Double? =
        if (isNull(key)) null else getDouble(key)

    private fun JSONObject.nullableFloat(key: String): Float? = nullableDouble(key)?.toFloat()

    private fun JSONObject.nullableLong(key: String): Long? =
        if (isNull(key)) null else getLong(key)

    private fun JSONObject.nullableString(key: String): String? =
        if (isNull(key)) null else getString(key)

    private fun JSONArray.strings(): List<String> =
        (0 until length()).map(::getString)

    private fun JSONArray.objects(): List<JSONObject> =
        (0 until length()).map(::getJSONObject)

    private companion object {
        const val SCHEMA_VERSION = 1
        val SAFE_ID = Regex("[A-Za-z0-9_-]{1,100}")
        val FINGERPRINT = Regex("[a-f0-9]{64}")
    }
}
